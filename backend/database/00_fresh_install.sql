-- WARNING: FOR A BRAND NEW EMPTY patient_queue DATABASE ONLY.
-- Do not run this script on a populated database.
BEGIN;
CREATE TABLE doctor (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     name VARCHAR(255), age INTEGER NOT NULL, department VARCHAR(255));
CREATE TABLE patient (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(255), age INTEGER NOT NULL, contact VARCHAR(255));
CREATE TABLE app_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255), role VARCHAR(255));
CREATE TABLE queue_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doctor_id BIGINT NOT NULL REFERENCES doctor(id), patient_id BIGINT NOT NULL REFERENCES patient(id),
 token_number INTEGER NOT NULL, status VARCHAR(20) NOT NULL,
 service_date DATE NOT NULL, check_in_time TIMESTAMP NOT NULL,
 consultation_start_time TIMESTAMP, consultation_end_time TIMESTAMP,
 CONSTRAINT uk_doctor_date_token UNIQUE (doctor_id,service_date,token_number)
);
CREATE TABLE daily_queue_counter (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doctor_id BIGINT NOT NULL, service_date DATE NOT NULL, last_token_number INTEGER NOT NULL,
 CONSTRAINT uk_doctor_service_date UNIQUE(doctor_id,service_date)
);
CREATE UNIQUE INDEX uq_active_patient_per_doctor_day ON queue_entry(patient_id,doctor_id,service_date)
 WHERE status IN ('WAITING','IN_CONSULTATION');
CREATE UNIQUE INDEX uq_one_consultation_per_doctor_day ON queue_entry(doctor_id,service_date)
 WHERE status='IN_CONSULTATION';
COMMIT;
