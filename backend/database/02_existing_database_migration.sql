-- For a BACKED-UP existing patient_queue database, after running preflight.
-- LocalDateTime timestamps are interpreted as the clinic's existing local wall-clock timestamps.
-- This is intentionally non-destructive; duplicate or missing legacy data aborts the transaction.
BEGIN;
LOCK TABLE queue_entry IN ACCESS EXCLUSIVE MODE;
ALTER TABLE queue_entry ADD COLUMN IF NOT EXISTS service_date DATE;
UPDATE queue_entry SET service_date = check_in_time::date WHERE service_date IS NULL AND check_in_time IS NOT NULL;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM queue_entry WHERE service_date IS NULL OR check_in_time IS NULL) THEN
     RAISE EXCEPTION 'Migration blocked: records have missing visit/check-in dates';
  END IF;
  IF EXISTS (SELECT 1 FROM queue_entry GROUP BY doctor_id,service_date,token_number HAVING COUNT(*)>1) THEN
     RAISE EXCEPTION 'Migration blocked: duplicate token numbers within doctor/day';
  END IF;
  IF EXISTS (SELECT 1 FROM queue_entry WHERE status IN ('WAITING','IN_CONSULTATION')
      GROUP BY patient_id,doctor_id,service_date HAVING COUNT(*)>1) THEN
     RAISE EXCEPTION 'Migration blocked: duplicate active check-ins';
  END IF;
  IF EXISTS (SELECT 1 FROM queue_entry WHERE status='IN_CONSULTATION'
      GROUP BY doctor_id,service_date HAVING COUNT(*)>1) THEN
     RAISE EXCEPTION 'Migration blocked: multiple active consultations for a doctor/day';
  END IF;
END $$;
ALTER TABLE queue_entry ALTER COLUMN service_date SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_doctor_date_token ON queue_entry(doctor_id,service_date,token_number);
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_patient_per_doctor_day ON queue_entry(patient_id,doctor_id,service_date)
 WHERE status IN ('WAITING','IN_CONSULTATION');
CREATE UNIQUE INDEX IF NOT EXISTS uq_one_consultation_per_doctor_day ON queue_entry(doctor_id,service_date)
 WHERE status='IN_CONSULTATION';
CREATE TABLE IF NOT EXISTS daily_queue_counter (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doctor_id BIGINT NOT NULL, service_date DATE NOT NULL, last_token_number INTEGER NOT NULL,
 CONSTRAINT uk_doctor_service_date UNIQUE (doctor_id,service_date)
);
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM daily_queue_counter GROUP BY doctor_id, service_date HAVING COUNT(*)>1) THEN
   RAISE EXCEPTION 'Migration blocked: existing daily counters are duplicated';
 END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS uk_doctor_service_date ON daily_queue_counter(doctor_id,service_date);
INSERT INTO daily_queue_counter(doctor_id,service_date,last_token_number)
 SELECT doctor_id,service_date,MAX(token_number) FROM queue_entry GROUP BY doctor_id,service_date
 ON CONFLICT (doctor_id,service_date) DO UPDATE
 SET last_token_number=GREATEST(daily_queue_counter.last_token_number,EXCLUDED.last_token_number);
COMMIT;
